interface I18nContextType {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  locale: "en",
  setLocale: () => {},
  t: (key) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    // Load from localStorage first for instant rendering
    const stored = localStorage.getItem("turbo-locale") as Locale | null;
    if (stored && (stored === "en" || stored === "nl")) {
      setLocaleState(stored);
    }
    // Then fetch server-side profile (creates it if missing) and apply its locale
    import("./api").then(({ profileApi }) => {
      profileApi.get().then((profile) => {
        if (profile?.locale && (profile.locale === "en" || profile.locale === "nl")) {
          setLocaleState(profile.locale as Locale);
          localStorage.setItem("turbo-locale", profile.locale);
        }
      }).catch(() => {});
    });
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    localStorage.setItem("turbo-locale", l);
    // Persist to backend profile
    import("./api").then(({ profileApi }) => {
      profileApi.updateLocale(l).catch(() => {});
    });
  }, []);

  const t = useCallback(
    (key: string) => translations[locale]?.[key] ?? translations.en[key] ?? key,
    [locale]
  );

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
